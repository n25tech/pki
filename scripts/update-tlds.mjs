#!/usr/bin/env node
// Regenerates src/shared/tlds.ts from IANA's list of top-level domains.
// Run: npm run update-tlds
import { writeFileSync } from "node:fs";

const SOURCE = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt";
const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
const text = await res.text();
const version = text.split("\n")[0].replace(/^#\s*/, "");
const tlds = text
  .split("\n")
  .map((l) => l.trim().toLowerCase())
  .filter((l) => l && !l.startsWith("#"));
if (tlds.length < 1000 || !tlds.includes("com")) throw new Error(`Unexpected list (${tlds.length} entries)`);

// Wrap at ~100 columns to keep diffs readable.
const lines = [];
let line = "";
for (const t of tlds) {
  const item = `"${t}",`;
  if (line.length + item.length + 1 > 100) {
    lines.push(line);
    line = "";
  }
  line += (line ? " " : "") + item;
}
if (line) lines.push(line);

writeFileSync(
  new URL("../src/shared/tlds.ts", import.meta.url),
  `// Generated by scripts/update-tlds.mjs from ${SOURCE}. Do not edit by hand.
// ${version}
// prettier-ignore
export const IANA_TLDS: ReadonlySet<string> = new Set([
${lines.map((l) => `  ${l}`).join("\n")}
]);
`,
);
console.log(`Wrote ${tlds.length} TLDs (${version})`);
