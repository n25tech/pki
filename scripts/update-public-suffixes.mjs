#!/usr/bin/env node
// Regenerates src/shared/publicSuffixes.ts from:
//   - the Public Suffix List (ICANN and private sections), e.g. co.uk, github.io, *.ck
//   - IANA's list of top-level domains (in case a new TLD isn't on the PSL yet)
// Run: npm run update-public-suffixes
import { writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";

async function get(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

const PSL = "https://publicsuffix.org/list/public_suffix_list.dat";
const IANA = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt";
const [psl, iana] = await Promise.all([get(PSL), get(IANA)]);

const toAscii = (name) => {
  const ascii = domainToASCII(name);
  if (!ascii) throw new Error(`Can't convert "${name}" to ASCII`);
  return ascii.toLowerCase();
};

const exact = new Set();
const wildcard = new Set(); // "*.ck" stored as "ck"
const exception = new Set(); // "!www.ck" stored as "www.ck"
for (const raw of psl.split("\n")) {
  const rule = raw.trim().split(/\s/)[0];
  if (!rule || rule.startsWith("//")) continue;
  if (rule.startsWith("!")) exception.add(toAscii(rule.slice(1)));
  else if (rule.startsWith("*.")) wildcard.add(toAscii(rule.slice(2)));
  else exact.add(toAscii(rule));
}
const ianaVersion = iana.split("\n")[0].replace(/^#\s*/, "");
for (const line of iana.split("\n")) {
  const t = line.trim().toLowerCase();
  if (t && !t.startsWith("#")) exact.add(t);
}
if (exact.size < 9000 || !exact.has("co.uk") || !exact.has("com")) {
  throw new Error(`Unexpected lists (${exact.size} rules)`);
}

const set = (values) => {
  const lines = [];
  let line = "";
  for (const v of [...values].sort()) {
    const item = `"${v}",`;
    if (line.length + item.length + 1 > 110) {
      lines.push(line);
      line = "";
    }
    line += (line ? " " : "") + item;
  }
  if (line) lines.push(line);
  return `new Set([\n${lines.map((l) => `  ${l}`).join("\n")}\n])`;
};

writeFileSync(
  new URL("../src/shared/publicSuffixes.ts", import.meta.url),
  `// Generated by scripts/update-public-suffixes.mjs. Do not edit by hand.
// Sources: ${PSL} (fetched ${new Date().toISOString().slice(0, 10)})
//          ${IANA} (${ianaVersion})
// Names are lower-case ASCII (IDNs in punycode).
/* prettier-ignore */
export const PUBLIC_SUFFIXES: ReadonlySet<string> = ${set(exact)};

/** Wildcard rules: "*.ck" is stored as "ck", so any "<label>.ck" is a public suffix. */
/* prettier-ignore */
export const PUBLIC_SUFFIX_WILDCARDS: ReadonlySet<string> = ${set(wildcard)};

/** Exceptions to wildcard rules: "!www.ck" is stored as "www.ck". */
/* prettier-ignore */
export const PUBLIC_SUFFIX_EXCEPTIONS: ReadonlySet<string> = ${set(exception)};
`,
);
console.log(`Wrote ${exact.size} suffixes, ${wildcard.size} wildcards, ${exception.size} exceptions`);
